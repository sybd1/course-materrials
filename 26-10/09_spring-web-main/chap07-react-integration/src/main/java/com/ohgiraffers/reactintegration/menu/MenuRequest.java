package com.ohgiraffers.reactintegration.menu;

public class MenuRequest {

    private String name;
    private int price;

    public MenuRequest() {
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getPrice() {
        return price;
    }

    public void setPrice(int price) {
        this.price = price;
    }
}
